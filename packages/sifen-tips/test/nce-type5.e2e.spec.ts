import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import type { FacturaPocInput, QrConfig } from '@sifen/sifen-gateway';
import { validateXml } from '@sifen/sifen-xsd';
import { generateDevCertificate } from './support/dev-certificate.ts';
import { restoreNoSubprocessGuard } from './support/no-subprocess-guard.ts';
import { pocFacturaInput } from './fixtures/poc-factura-input.ts';

const QR_CONFIG: QrConfig = {
  idCsc: '0001',
  csc: 'ABCD0000000000000000000000000000',
  ambiente: 'test',
};

/** CDC of an FE (type 01) the NCE is associated to. Shape only: no real document. */
const ASSOCIATED_CDC = '01800000019001001000000112026101310000000019';

/** Credit-note input derived from the FE fixture: the groups of an FE that an NCE must not carry are dropped. */
function creditNoteInput(tipoTransaccion: number | undefined): FacturaPocInput {
  const rest = Object.fromEntries(
    Object.entries(pocFacturaInput.data).filter(
      ([key]) => key !== 'factura' && key !== 'condicion',
    ),
  );
  return {
    params: pocFacturaInput.params,
    data: {
      ...rest,
      tipoDocumento: 5,
      ...(tipoTransaccion === undefined ? {} : { tipoTransaccion }),
      notaCreditoDebito: { motivo: 2 },
      documentoAsociado: { formato: 1, cdc: ASSOCIATED_CDC },
    },
  };
}

/**
 * HU-E7-01 T2 spike (ADR-0019): what `xmlgen` produces for iTiDE 5, offline.
 * Proves the XSD accepts it and settles the `tipoTransaccion` handling (D9).
 */
describe('TIPS spike: NCE (iTiDE 5) generated by xmlgen', () => {
  let xml: string;
  let signedXmlWithQr: string;

  beforeAll(async () => {
    const { TipsDeXmlBuilder, TipsQrGenerator, TipsXmlSigner } = await import('../src/index.ts');
    xml = await new TipsDeXmlBuilder().buildParaSifen(creditNoteInput(1));
    signedXmlWithQr = await new TipsQrGenerator().addQr(
      await new TipsXmlSigner().sign(xml, generateDevCertificate()),
      QR_CONFIG,
    );
  });

  afterAll(() => {
    restoreNoSubprocessGuard();
  });

  it('validates against siRecepDE once signed', () => {
    const result = validateXml(signedXmlWithQr, 'siRecepDE');
    expect(result.errors).toEqual([]);
    expect(result.valid).toBe(true);
  });

  it('carries iTiDE 5, the reason and the association to the FE CDC', () => {
    expect(xml).toMatch(/<iTiDE>5<\/iTiDE>/);
    expect(xml).toMatch(/<dDesTiDE>Nota de crédito electrónica<\/dDesTiDE>/);
    expect(xml).toMatch(
      /<gCamNCDE><iMotEmi>2<\/iMotEmi><dDesMotEmi>[^<]+<\/dDesMotEmi><\/gCamNCDE>/,
    );
    expect(xml).toMatch(
      new RegExp(
        `<gCamDEAsoc><iTipDocAso>1</iTipDocAso>.*<dCdCDERef>${ASSOCIATED_CDC}</dCdCDERef>`,
      ),
    );
  });

  it('omits the groups that only an FE carries', () => {
    expect(xml).not.toContain('<gCamCond>');
    expect(xml).not.toContain('<gCamFE>');
    expect(xml).not.toContain('<iTipTra>');
    expect(xml).not.toContain('<gTransp>');
  });

  it('keeps the commercial operation group with currency and tax type', () => {
    expect(xml).toMatch(/<gOpeCom><iTImp>1<\/iTImp>.*<cMoneOpe>PYG<\/cMoneOpe>/);
  });

  it('D9: tipoTransaccion is optional for type 5 and never emitted, so the platform omits it', async () => {
    const { TipsDeXmlBuilder } = await import('../src/index.ts');
    const builder = new TipsDeXmlBuilder();
    for (const tipoTransaccion of [undefined, 1, 2]) {
      const built = await builder.buildParaSifen(creditNoteInput(tipoTransaccion));
      expect(built).not.toContain('<iTipTra>');
    }
  });
});
